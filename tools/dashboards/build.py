def level_forecast(valid, level):
    return f"""const now = Date.now();
const a = entity.attributes;
const valid = hass.states['{valid}'];
if (['unknown', 'unavailable'].includes(entity.state) ||
    (!a.refreshing && (valid?.state !== 'on' || !(Date.parse(a.valid_until) > now)))) return [];
const left = Math.max(now, start.getTime());
const coverage = Date.parse(valid?.attributes?.coverage_end);
const right = Math.min(end.getTime(), Number.isFinite(coverage) ? coverage : end.getTime());
if (right <= left) return [];
const points = new Map([[left, 0], [right, 0]]);
for (const row of (a.outlook || [])) {{
  const from = Math.max(left, Date.parse(row.start));
  const to = Math.min(right, Date.parse(row.end));
  if (!(to > from) || !['BOOST', 'CHEAP', 'NORMAL', 'LIMIT'].includes(row.level)) continue;
  const value = row.level === '{level}' ? 1 : 0;
  points.set(from, value);
  points.set(to - 1, value);
  points.set(to, 0);
}}
return [...points].sort((a, b) => a[0] - b[0]);
"""


def consumer_section(entities=ENTITIES, lang="en"):
    """Consumer Compass levels: 4 h of history and a 20 h forecast."""
    e, t = entities, LABELS[lang]
    chart = {
        "type": "custom:apexcharts-card",
        "section_mode": True,
        "grid_options": {"columns": "full", "rows": 4},
        "header": {"show": True, "title": t["consumer_title"], "show_states": False},
        "graph_span": "24h",
        "span": {"offset": "+20h"},
        "update_interval": "1min",
        "hours_12": False,
        "now": {"show": True, "label": t["now"], "color": "#ffb300"},
        "yaxis": [{"min": 0, "max": 1, "show": False}],
        "apex_config": {
            "chart": {
                "animations": {"enabled": False},
                "toolbar": {"show": False},
                "zoom": {"enabled": False},
            },
            "grid": {
                "show": False,
                "padding": {"top": 10, "bottom": 0, "left": 8, "right": 8},
            },
            "markers": {"size": 0},
            "dataLabels": {"enabled": False},
            "xaxis": {
                "labels": {
                    "datetimeUTC": False,
                    "format": "HH:mm",
                    "hideOverlappingLabels": True,
                },
                "tooltip": {"enabled": False},
                "axisBorder": {"show": False},
                "axisTicks": {"show": False},
            },
            "legend": {
                "show": True,
                "position": "bottom",
                "fontSize": "12px",
                "customLegendItems": list(LEVEL_COLORS),
                "markers": {"fillColors": list(LEVEL_COLORS.values())},
                "onItemClick": {"toggleDataSeries": False},
                "onItemHover": {"highlightDataSeries": False},
            },
            "tooltip": {
                "shared": False,
                "intersect": False,
                "custom": f"""EVAL:function({{seriesIndex, dataPointIndex, w}}) {{
  const value = w.globals.series[seriesIndex]?.[dataPointIndex];
  if (value !== 1) return '';
  const timestamp = w.globals.seriesX[seriesIndex]?.[dataPointIndex];
  if (!Number.isFinite(timestamp)) return '';
  const name = w.globals.seriesNames[seriesIndex];
  const date = new Date(timestamp).toLocaleString('{t["locale"]}', {{day:'2-digit', month:'2-digit', hour:'2-digit', minute:'2-digit'}});
  return '<div style="padding:8px 12px"><b>' + name + '</b><br>' + date + '</div>';
}}""",
            },
        },
        "series": [],
    }
    for projected in (False, True):
        for level, color in LEVEL_COLORS.items():
            series = {
                "entity": e["plan"] if projected else e["consumer"],
                "name": f"{level} · {t['forecast'] if projected else t['history']}",
                "color": color,
                "type": "area",
                "curve": "stepline",
                "stroke_width": 0,
                "opacity": 0.55 if projected else 1,
                "extend_to": False if projected else "now",
                "show": {"in_header": False, "legend_value": False},
            }
            if projected:
                series["data_generator"] = level_forecast(e["valid"], level)
            else:
                series["transform"] = f"return x === '{level}' ? 1 : 0;"
                series["fill_raw"] = "zero"
            chart["series"].append(series)
    note = {
        "type": "markdown",
        "grid_options": {"columns": "full", "rows": "auto"},
        "content": f"""**{t["now"]}: {{{{ states('{e["consumer"]}') }}}}** · {t["consumer_note"]}
{{% if state_attr('{e["plan"]}', 'refreshing') == true %}}
{t["consumer_refreshing"]}
{{% elif not is_state('{e["valid"]}', 'on') %}}
{t["consumer_stale"]}
{{% endif %}}""",
    }
    return {"type": "grid", "column_span": 4, "cards": [chart, note]}


