def plan_guard(valid):
    return f"""const now = Date.now();
const valid = hass.states['{valid}'];
// The integration retains the last complete generation while its replacement runs.
const refreshing = entity.attributes.refreshing === true;
if (['unknown', 'unavailable'].includes(entity.state) ||
    (!refreshing && (valid?.state !== 'on' ||
      !(Date.parse(entity.attributes.valid_until) > now)))) return [];
const rows = (entity.attributes.intervals || []).filter(r =>
  Number.isFinite(Date.parse(r.start)) && Number.isFinite(Date.parse(r.end)) &&
  Date.parse(r.end) > Date.parse(r.start) && Date.parse(r.end) > now
).sort((a, b) => Date.parse(a.start) - Date.parse(b.start));
const points = [];
"""


def power_generator(valid, field):
    expression = (
        "r.grid_import_kwh - r.grid_export_kwh" if field == "grid" else f"r.{field}_kwh"
    )
    required = (
        "Number.isFinite(r.grid_import_kwh) && Number.isFinite(r.grid_export_kwh)"
        if field == "grid"
        else f"Number.isFinite(r.{field}_kwh)"
    )
    return (
        plan_guard(valid)
        + f"""let previousEnd = null;
let previousValue = null;
for (const r of rows) {{
  const from = Date.parse(r.start), to = Date.parse(r.end);
  const value = ({required}) ? ({expression}) / ((to - from) / 3600000) : null;
  // Clip the first slot at now, but divide by its original duration.
  const left = Math.max(from, now);
  if (previousEnd !== null && from > previousEnd) {{
    points.push([previousEnd, previousValue], [previousEnd + 1, null]);
  }}
  points.push([left, value]);
  previousEnd = to;
  previousValue = value;
}}
if (previousEnd !== null) points.push([previousEnd, previousValue]);
return points;
"""
    )


def soc_generator(valid, soc, capacity):
    return (
        plan_guard(valid)
        + f"""const capacityKwh = {capacity};
const raw = hass.states['{soc}']?.state;
const current = raw == null || raw === '' ? NaN : Number(raw);
let previousEnd = null;
for (const r of rows) {{
  const from = Date.parse(r.start), to = Date.parse(r.end);
  if (previousEnd === null && from <= now && Number.isFinite(current)) {{
    points.push([now, current]);
  }} else if (previousEnd !== null && from > previousEnd) {{
    points.push([previousEnd + 1, null]);
  }}
  const value = Number.isFinite(r.end_soc_kwh) ? r.end_soc_kwh / capacityKwh * 100 : null;
  points.push([to, value]);
  previousEnd = to;
}}
return points;
"""
    )


